import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const packageJsonPath = require.resolve("kiso.css/package.json");
const cssPath = join(dirname(packageJsonPath), "kiso.css");
const outputPath = join(dirname(fileURLToPath(import.meta.url)), "../src/kiso-css.ts");

const css = await readFile(cssPath, "utf8");
const source = `// This file is generated by scripts/generate-kiso-css.mjs from kiso.css.
export const KISO_CSS = ${JSON.stringify(css)};
`;

await writeFile(outputPath, source);
